import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hover?: boolean; glass?: boolean }
>(({ className, hover = false, glass = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-3xl border border-slate-200/80 bg-white text-slate-950 shadow-xs transition-all duration-300",
      glass && "bg-white/85 backdrop-blur-xl border-slate-200/70 shadow-sm",
      hover && "hover:-translate-y-1 hover:shadow-xl hover:shadow-indigo-500/5 hover:border-indigo-200/80",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

